#!/usr/bin/env node
// Writes src/design/chosen/: the design sections the site's pages render, one file per page.
//
//   node scripts/chosen.mjs        production (npm run build): only the offers chosen in design/decisions.json
//   node scripts/chosen.mjs --all  development (npm run dev): the whole gallery, so a pick in /design shows at once
//
//   chosen/home.ts       `sections`: every section that isn't a whole page (the home page stitches these together)
//   chosen/<page-id>.ts  `section`: one whole-page section (kind "page"), e.g. chosen/page-otp.ts for /virtual-number
//
// Why: src/design/registry.ts imports every offer ever designed (hundreds of components). A page that imports it
// ships all of them to the browser although it shows one, and a single shared list would still give every page the
// other pages' designs. So each page imports only its own file, which imports only the chosen offer.
//
// The registry's section list is plain data (strings, ids and component names), so it is read by turning each
// `Component: X` / `context: X` into the string "X" and evaluating the array; the imports for the kept names are
// copied from the registry's own import lines.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "src/design/chosen");
const header = "// Generated by scripts/chosen.mjs (npm run dev / npm run build). Do not edit; not committed.\n";
const all = process.argv.includes("--all");

const src = readFileSync(join(root, "src/design/registry.ts"), "utf8");
const decisions = JSON.parse(readFileSync(join(root, "design/decisions.json"), "utf8"));

// name used in the registry → how to import it
const imports = new Map();
for (const m of src.matchAll(/^import (?!type )(.+?) from "(.+?)";$/gm)) {
  const [, what, from] = m;
  const named = what.match(/\{(.*)\}/);
  const def = what.replace(/\{.*\}/, "").replace(/,\s*$/, "").trim();
  if (def) imports.set(def, { from, def: true });
  if (named) {
    for (const spec of named[1].split(",").map((s) => s.trim()).filter(Boolean)) {
      const [orig, alias] = spec.split(/\s+as\s+/);
      imports.set((alias ?? orig).trim(), { from, spec });
    }
  }
}

const start = src.indexOf("export const sections: Section[] = [");
const end = src.indexOf("\n];", start);
if (start < 0 || end < 0) throw new Error("chosen.mjs: can't find `export const sections` in registry.ts");
const body = src
  .slice(src.indexOf("[", start), end + 2)
  .replace(/\b(Component|context): ([A-Za-z_$][\w$]*)/g, (_, k, name) => `${k}: ${JSON.stringify(name)}`)
  // An offer list kept in its own file (the logo's): no page renders it from here (the logo comes through
  // components/brand), so it is left empty.
  .replace(/\boffers: ([A-Za-z_$][\w$]*)/g, "offers: []");
const sections = new Function(`return ${body};`)();

const pages = sections.filter((s) => s.kind === "page");
const homeSections = sections.filter((s) => s.kind !== "page");

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });
const write = (name, code) => writeFileSync(join(outDir, name), header + code);

if (all) {
  write("home.ts", `export { sections } from "../registry";\n`);
  for (const p of pages) {
    write(`${p.id}.ts`, `import { getSection } from "../registry";\n\nexport const section = getSection(${JSON.stringify(p.id)})!;\n`);
  }
  console.log(`chosen designs: development, whole gallery (${pages.length} pages)`);
  process.exit(0);
}

// A page with no choice yet falls back to offer A (L for the virtual-number page) in its page file.
const FALLBACKS = ["A", "L"];
const keep = (s) => {
  const chosen = s.offers.find((o) => o.id === decisions[s.id]?.offer);
  const offers = chosen ? [chosen] : s.kind === "page" ? s.offers.filter((o) => FALLBACKS.includes(o.id)) : [];
  return offers.length ? { ...s, offers } : null;
};

const code = (v) => (typeof v === "string" ? JSON.stringify(v) : String(v));
const offerCode = (o) => `{ ${Object.entries(o).map(([k, v]) => `${k}: ${k === "Component" ? v : code(v)}`).join(", ")} }`;
const sectionCode = (s) => {
  const fields = Object.entries(s).filter(([k]) => k !== "offers").map(([k, v]) => `${k}: ${k === "context" ? v : code(v)}`);
  return `{ ${fields.join(", ")}, offers: [${s.offers.map(offerCode).join(", ")}] }`;
};

// The import lines for the components these sections use.
function importsFor(kept) {
  const used = new Set(kept.flatMap((s) => [...s.offers.map((o) => o.Component), ...(s.context ? [s.context] : [])]));
  const missing = [...used].filter((n) => !imports.has(n));
  if (missing.length) throw new Error(`chosen.mjs: no import line in registry.ts for ${missing.join(", ")}`);
  const byFile = new Map();
  for (const name of used) {
    const imp = imports.get(name);
    const f = byFile.get(imp.from) ?? { def: null, specs: [] };
    if (imp.def) f.def = name;
    else f.specs.push(imp.spec);
    byFile.set(imp.from, f);
  }
  const lines = [...byFile].map(([from, f]) => {
    const parts = [f.def, f.specs.length ? `{ ${f.specs.join(", ")} }` : null].filter(Boolean).join(", ");
    return `import ${parts} from ${JSON.stringify(from.replace(/^\.\//, "../"))};`;
  });
  return { lines, count: used.size };
}

const home = homeSections.map(keep).filter(Boolean);
const homeImports = importsFor(home);
write(
  "home.ts",
  `import type { Section } from "../registry";\n${homeImports.lines.join("\n")}\n\n` +
    `export const sections: Section[] = [\n${home.map((s) => `  ${sectionCode(s)},`).join("\n")}\n];\n`,
);

let pageComponents = 0;
for (const p of pages) {
  const kept = keep(p) ?? { ...p, offers: [] };
  const { lines, count } = importsFor([kept]);
  pageComponents += count;
  write(`${p.id}.ts`, `import type { Section } from "../registry";\n${lines.join("\n")}\n\nexport const section: Section = ${sectionCode(kept)};\n`);
}
console.log(`chosen designs: home ${home.length} sections / ${homeImports.count} components; ${pages.length} pages / ${pageComponents} components`);
